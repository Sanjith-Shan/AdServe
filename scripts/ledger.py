"""Builds NUMBERS_LEDGER.md from results/*.jsonl so no figure is copied by hand.
Run: python3 scripts/ledger.py"""
import json, os, statistics
from collections import defaultdict

R = "results"

def rows(f):
    p = os.path.join(R, f)
    return [json.loads(l) for l in open(p)] if os.path.exists(p) else []

def machine(o):
    m = o.get("machine", {})
    lp = f", low power mode {m['low_power_mode']}" if m.get('low_power_mode') else ""
    return f"{m.get('cpu','?')} ({m.get('os','?')}), {m.get('cores','?')} cores, {m.get('memory_gb','?')} GB{lp}"

out = ["# Numbers ledger", "",
       "Generated by `scripts/ledger.py` from `results/*.jsonl`. Every row names its file. Every latency",
       "run is on one laptop with the load generator on the same machine, which was shared with another",
       "project's benchmarks; the two took turns through a lock (`scripts/lib.sh`). The CPU-only auction",
       "simulations (experiments 11, 12, 14, 15, 16) ran on a separate Windows machine; each section",
       "names its machine.",
       "`results/archive/` holds superseded runs and is never quoted.", ""]

# exp1 / exp6 / exp9: bursts
def burst_table(file, title, note):
    rs = rows(file)
    if not rs: return
    out.extend([f"## {title}", "", note, "",
                f"File `results/{file}`. Machine: {machine(rs[0])}. Burst: N requests in 2 s, gamma arrival (k=2, theta 0.4 s), all LIVE, fresh simulated viewers per repeat, real ad-break contexts from iPinYou 2013-06-11. Latency is from each request's intended send time (open loop).", "",
                "| Label | N in 2 s | Offered peak /s | Repeat | OK | Error rate | p50 ms | p99 ms | p99.9 ms | Ads per pod | Load avg before |",
                "|---|---|---|---|---|---|---|---|---|---|---|"])
    for o in rs:
        L = o["live"]
        out.append(f"| {o['label']} | {o['burst_requests']:,} | {o['offered_peak_per_s']:,.0f} | {o['repeat']} | {L['ok']:,} | {L['error_rate']:.4f} | {L['p50_ms']:.2f} | {L['p99_ms']:.2f} | {L['p999_ms']:.2f} | {L['mean_ads_per_pod']:.2f} | {o.get('load_avg_before_burst','').strip('{} ').split(' ')[0]} |")
    out.append("")
    notes = sorted({(o['label'], o.get('note', '')) for o in rs if o.get('note')})
    for l, n in notes: out.append(f"- `{l}`: {n}")
    if notes: out.append("")

burst_table("exp1_burst.jsonl", "Experiment 1: live-break burst, AdServe against a synchronous database write",
            "`adserve` logs each decision to Kafka without waiting; `legacy_sync_write` inserts it into Postgres before responding.")

