            out.append(f"| {o['leg']} | {c} | | {cl['mean']:+.2f}% ({cl['ci95'][0]:+.2f} to {cl['ci95'][1]:+.2f}) | {cp['mean']:+.2f}% | {cp['ci95'][0]:+.2f} to {cp['ci95'][1]:+.2f} | {e['mean']:.3f} ({e['ci95'][0]:.3f} to {e['ci95'][1]:.3f}) | | {o['per_click_billing_delta_cost_per_true_click_pct']['mean']:+.2f}% |")
